"""Rebuild every gallery source from the committed case records and check its archive hash."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

from index_campaign import read,write,RESULTS

ROOT=RESULTS.parents[1]
CODE=ROOT/"research/shape_search_20261121"


def regenerate(job,out,registry):
    pair,item=job
    track=pair["track"]
    n=str(item["case"])
    target=(out/item["cloud"]).resolve()
    assert target.is_relative_to(out)
    virtual=f"results/shape_search_20261121/clouds/{track}-{n}.npz"
    expected=registry[virtual]["sha256"]
    if target.exists():
        raise FileExistsError(f"Choose a fresh replay directory: {target}")
    with tempfile.TemporaryDirectory(dir=out) as scratch:
        scratch=Path(scratch)
        result=scratch/"points.npz"
        if track in ("flows","links","cycles"):
            argv=[CODE/"flows/replay_case.py","--case",n,"--out",result]
            if track=="links":
                argv.append("--linked")
        elif track=="maps":
            argv=[CODE/"maps/replay.py",n,"--output",result]
        elif track=="projection":
            rec=RESULTS/"projection"/f"case-{n}.json"
            if not rec.exists():
                rec=RESULTS/"projection/three"/f"case-{n}.json"
            argv=[CODE/"projection/reproduce.py","--record",rec,"--out",result]
        elif track in ("braids","pinched","delay"):
            result=scratch/f"case-{n}.npz"
            if track=="braids":
                argv=[CODE/"braids/sample.py",RESULTS/"braids/certificates.json","--steps","480000"]
            elif track=="pinched":
                argv=[CODE/"pinched/search.py","--replay",RESULTS/"pinched/manifest.json","--steps","240000"]
            else:
                argv=[CODE/"delay/confirm.py",RESULTS/"delay/manifest.json","--long"]
            argv.extend(["--cases",n,"--out",scratch])
        else:
            raise ValueError(track)
        env={**os.environ,"OPENBLAS_NUM_THREADS":"1","NUMBA_NUM_THREADS":"1","OMP_NUM_THREADS":"1"}
        proc=subprocess.run([sys.executable,*map(str,argv)],cwd=ROOT,env=env,capture_output=True,text=True)
        if proc.returncode:
            raise RuntimeError(proc.stderr+proc.stdout)
        with result.open("rb") as f:
            actual=hashlib.file_digest(f,"sha256").hexdigest()
        assert actual==expected,(track,n,expected,actual)
        target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(result,target)
    return {"track":track,"case":int(n),"file":item["cloud"],"sha256":actual}


def run(out,workers):
    out.mkdir(parents=True,exist_ok=True)
    out=out.resolve()
    registry={row["path"]:row for row in read(ROOT/"records/generated-data.json")["files"]}
    jobs=[(pair,case) for pair in read(RESULTS/"presentation.json") for case in pair["cases"]]
    assert len(jobs)==len({case["cloud"] for _,case in jobs})
    with ThreadPoolExecutor(max_workers=workers) as pool:
        records=list(pool.map(lambda job:regenerate(job,out,registry),jobs))
    write(out/"replayed-portraits.json",records)
    print(f"{len(records)} gallery inputs regenerated byte for byte",flush=True)


if __name__=="__main__":
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out",required=True,type=Path)
    ap.add_argument("--workers",default=2,type=int)
    args=ap.parse_args()
    run(args.out,args.workers)
