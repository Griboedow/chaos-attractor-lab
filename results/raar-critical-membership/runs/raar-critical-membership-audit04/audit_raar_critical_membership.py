"""Audit critical-point evidence and the exact dependency chain into trapping Q.

Checks complete partitions and stored inequalities; image arithmetic is
regenerated by the separate primary/automatic-derivative implementations.
The crossing-continuum and fold arguments remain explicit mathematical proofs.
"""
import argparse
import gzip
import json
from collections import Counter
from decimal import Decimal
from fractions import Fraction
from pathlib import Path
from audit_raar_coverings import bounds, sha, audit_partition


def read(p):return json.loads(p.read_text())


def partition(records,dimensions):
    tree={};depths=Counter();count=0
    for record in records:
        branch=record['path'];assert len(branch)%2==0;node=tree
        for i in range(0,len(branch),2):
            token=branch[i:i+2]
            assert token[0] in dimensions and token[1] in '01' and '#' not in node
            node=node.setdefault(token,{})
        assert not node;node['#']=True;count+=1;depths[len(branch)//2]+=1
    def visit(node):
        if '#' in node:assert set(node)=={'#'};return 1
        keys=sorted(node)
        assert len(keys)==2 and keys[0][0]==keys[1][0] and keys[0][1]=='0' and keys[1][1]=='1'
        return sum(visit(v) for v in node.values())
    assert visit(tree)==count
    assert sum(Fraction(n,2**d) for d,n in depths.items())==1
    return count,max(depths)


def lines(p):
    with gzip.open(p,'rt',encoding='utf-8') as stream:return [json.loads(v) for v in stream]


def source_bindings(folder,report):
    assert sha(folder/'input.json')==report['input_sha256']
    if 'source_sha256' in report:
        name='certify_raar_critical_crossing.py' if 'steps' in report else 'certify_raar_coverings.py'
        assert sha(folder/name)==report['source_sha256']
    if 'enclosure_source_sha256' in report:assert sha(folder/'certify_raar_critical_doubleton.py')==report['enclosure_source_sha256']
    if 'second_source_sha256' in report:assert sha(folder/'check_raar_coverings_ad.py')==report['second_source_sha256']
    for field in ['sources','second_sources']:
        for name,digest in report.get(field,{}).items():assert sha(folder/name)==digest


def main(args):
    repo=Path(__file__).resolve().parents[1];base=args.base
    raw=read(base/'raar-critical-thin-window01/input.json')
    original_path=repo/'results/raar-symbolic-dynamics/runs/raar-covering-refined01/input.json'
    original=read(original_path);assert raw.keys()==original.keys()
    for key in raw:
        if key!='radii':assert raw[key]==original[key]
    assert raw['radii'][1:]==original['radii'][1:]
    assert all(0<Fraction(a)<=Fraction(b) for a,b in zip(raw['radii'][0],original['radii'][0]))
    assert raw['radii'][0][0]==original['radii'][0][0]
    manifest_hashes={}
    for name in ['raar-symbolic-dynamics','raar-trapping']:
        packet=repo/'results'/name;manifest=read(packet/'manifest.json')
        for row in manifest['files']:
            p=packet/row['path'];assert sha(p)==row['sha256'] and p.stat().st_size==row['bytes']
        manifest_hashes[name]=sha(packet/'manifest.json')
    closure=read(repo/'results/raar-trapping/runs/raar-trapping-closure-audit01/report.json')
    assert closure['status']=='closed_accounting_verified' and closure['new_unprocessed_cells']==0
    assert closure['axis_lower_bound']>0 and closure['image_margin_exact'][0]>0
    assert len(closure['exact_window_inclusion'])==7
    cover_rows=[]
    for name in ['raar-critical-thin-cover01','raar-critical-thin-cover-ad01']:
        folder=base/name;report=read(folder/'report.json');source_bindings(folder,report)
        assert report['status']=='passed' and report['edges']==[0] and read(folder/'input.json')==raw
        assert {r['kind'] for r in report['checks']}=={'volume','left','right'}
        for r in report['checks']:
            cert=folder/f"edge-0-{r['kind']}.jsonl.gz";assert sha(cert)==r['certificate_sha256']
            result=audit_partition(cert,r['kind'],int(raw['orientation'][0]))
            assert result['cells']==r['accepted'] and 2*r['accepted']-1==r['examined'] and r['pending']==0
            cover_rows.append({'run':name,'kind':r['kind'],**result})
    face_rows=[]
    for name in ['raar-critical-thin-faces01','raar-critical-thin-faces-ad01','raar-critical-thin-faces-natural01']:
        folder=base/name;report=read(folder/'report.json');source_bindings(folder,report)
        assert report['status']=='passed' and report['window']==0 and report['steps']==42 and report['orientation']==1
        assert read(folder/'input.json')==raw and {r['face'] for r in report['checks']}=={-1,1}
        for r in report['checks']:
            cert=folder/f"face-{r['face']}.jsonl.gz";assert sha(cert)==r['certificate_sha256']
            records=lines(cert);count,depth=partition(records,'12')
            assert count==r['accepted'] and depth==r['maximum_depth'] and r['examined']==2*count-1 and r['pending']==0
            margin=Decimal('Infinity');axis=Decimal('Infinity')
            for record in records:
                lo,hi=bounds(record['determinant'])
                bound=lo if r['face']==1 else hi.copy_negate();assert bound>0; margin=min(margin,bound)
                a=bounds(record['minimum_axis'])[0];assert a>0;axis=min(axis,a)
                for v in record['image']:bounds(v)
            assert margin==bounds(r['absolute_determinant_lower'])[0] and axis==bounds(r['minimum_axis'])[0]
            face_rows.append({'run':name,'face':r['face'],'cells':count,'absolute_determinant_lower':str(margin),'minimum_axis':str(axis)})
    fold_result=None
    if args.fold:
        folder=base/args.fold;report=read(folder/'report.json');source_bindings(folder,report)
        assert report['status']=='passed' and report['window']==0 and report['steps']==42 and read(folder/'input.json')==raw
        cert=folder/'volume.jsonl.gz';assert sha(cert)==report['certificate_sha256'];records=lines(cert)
        count,depth=partition(records,'012');assert count==report['accepted'] and report['examined']==2*count-1 and depth==report['maximum_depth'] and report['pending']==0
        modes=Counter()
        for record in records:
            assert bounds(record['minimum_axis'])[0]>0
            for v in record['image']:bounds(v)
            mode=record['classification'];modes[mode]+=1
            if mode=='regular':
                lo,hi=bounds(record['determinant']);assert lo>0 or hi<0
            else:
                assert mode=='fold_if_critical'
                for field in ['minor','transversality']:
                    lo,hi=bounds(record[field]);assert lo>0 or hi<0
                assert record['rows'] in [[0,1],[0,2],[1,2]] and record['minor_component'] in [0,1,2]
        assert modes['regular']==report['regular_boxes'] and modes['fold_if_critical']==report['fold_boxes']
        fold_result={'run':args.fold,'cells':count,'maximum_depth':depth,'classifications':dict(modes),'report_sha256':sha(folder/'report.json')}
    args.out.mkdir(parents=True,exist_ok=False)
    result={'status':'passed','input_sha256':sha(base/'raar-critical-thin-window01/input.json'),'original_input_sha256':sha(original_path),'thin_window_contained_in_original_window':True,'dependency_manifests':manifest_hashes,'closure_report_sha256':sha(repo/'results/raar-trapping/runs/raar-trapping-closure-audit01/report.json'),'coverings':cover_rows,'faces':face_rows,'fold_classification':fold_result,'scope':'Complete partition, inequality, exact-window-containment and frozen-evidence-binding audit. Interval image inclusion is checked by the separate computations. Attractor membership uses the stated crossing-continuum lemma; no claim of injectivity failure restricted to K or historical novelty.'}
    (args.out/'report.json').write_text(json.dumps(result,indent=2)+'\n')
    (args.out/Path(__file__).name).write_bytes(Path(__file__).read_bytes())
    print(json.dumps({'status':result['status'],'covering_leaves':sum(r['cells'] for r in cover_rows),'face_leaves':sum(r['cells'] for r in face_rows),'fold':fold_result}),flush=True)


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--base',type=Path,required=True);p.add_argument('--out',type=Path,required=True);p.add_argument('--fold');main(p.parse_args())
